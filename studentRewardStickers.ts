/**
 * Generate formatted HTML badge string ready to copy or insert into Word docs / rich text
 */
export function generateStickerHtmlBadge(sticker: StudentSticker, studentName?: string, teacherName?: string, dateStr?: string): string {
  const studentLine = studentName ? `<div style="font-size: 11px; font-weight: bold; color: #1e3a8a; margin-top: 4px;">Khen ngợi em: ${studentName}</div>` : '';
  const teacherLine = teacherName ? `<div style="font-size: 10px; font-style: italic; color: #555555; margin-top: 2px;">Giáo viên: ${teacherName} ${dateStr ? `• ${dateStr}` : ''}</div>` : '';

  return `
<div style="display: inline-block; padding: 10px 16px; border-radius: 18px; border: 2px solid ${sticker.accentColor}; background: #ffffff; box-shadow: 0 4px 10px rgba(0,0,0,0.08); font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif; text-align: center; max-width: 240px; margin: 6px;">
  <div style="font-size: 32px; line-height: 1.1; margin-bottom: 2px;">${sticker.emoji}</div>
  <div style="font-size: 13px; font-weight: bold; color: #111827; text-transform: uppercase; letter-spacing: 0.5px;">${sticker.title}</div>
  ${sticker.scoreTag ? `<div style="display: inline-block; background: ${sticker.accentColor}; color: #ffffff; font-size: 10px; font-weight: 800; padding: 2px 8px; border-radius: 9999px; margin: 3px 0;">${sticker.scoreTag}</div>` : ''}
  <div style="font-size: 11px; color: #4b5563; font-style: italic; margin-top: 2px;">"${sticker.quote}"</div>
  ${studentLine}
  ${teacherLine}
</div>`.trim();
}
